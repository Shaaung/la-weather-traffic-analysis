import sys
from pyspark.sql import SparkSession
from pyspark.sql import functions as F

def main():
    # Parameter Validation & Path Configuration
    # Supports both command-line arguments and default fallback paths
    if len(sys.argv) == 5:
        acc_raw = sys.argv[1]
        weather_raw = sys.argv[2]
        acc_out = sys.argv[3]
        weather_out = sys.argv[4]
    else:
        print("No arguments provided. Using default paths for 'mgmtmsa405-26s-team13-data'...")
        bucket_name = "gs://mgmtmsa405-26s-team13-data"
        acc_raw = f"{bucket_name}/raw/accidents/US_Accidents_March23.csv"
        # Ensure the filename below matches your actual file in GCS (Check if it uses spaces or underscores)
        weather_raw = f"{bucket_name}/raw/weather/LA_Weather_2016-23Mar.csv"
        acc_out = f"{bucket_name}/processed/processed_accident"
        weather_out = f"{bucket_name}/processed/processed_weather"

    # Initialize Standard Spark Session
    # Standard builder is best practice for Dataproc Serverless (Batches)
    spark = SparkSession.builder \
        .appName("LA_Accident_Weather_Simple_Pipeline") \
        .getOrCreate()

    try:
        # Weather Data Transformation
        print(f"Reading RAW weather data from: {weather_raw}")
        weather_df = spark.read.csv(weather_raw, header=True, inferSchema=True)

        weather_processed = (
            weather_df.select("STATION", "NAME", "LATITUDE", "LONGITUDE", "DATE", "PRCP", "WT01", "WT02", "WT08")
            .fillna(0, subset=["PRCP", "WT01", "WT02", "WT08"])
            .withColumn("Weather_Date", F.to_date("DATE"))
            # Convert daily precipitation to an hourly estimate
            .withColumn("Hourly_PRCP", F.col("PRCP") / 24.0)
            .withColumn("Precipitation_Level",
                F.when(F.col("Hourly_PRCP") > 0.3, "heavy rain")
                 .when(F.col("Hourly_PRCP") >= 0.1, "moderate rain")
                 .when(F.col("Hourly_PRCP") > 0, "light rain")
                 .otherwise("no rain"))
            # Binary flag for low visibility conditions
            .withColumn("low_visibility",
                F.when((F.col("WT01") == 1) | (F.col("WT02") == 1) | (F.col("WT08") == 1), 1).otherwise(0))
        )

        # Accident Data Transformation
        print(f"Reading RAW accident data from: {acc_raw}")
        acc_df = spark.read.csv(acc_raw, header=True, inferSchema=True)

        acc_processed = (
            # Focus analysis on Los Angeles County
            acc_df.filter(F.col("County") == "Los Angeles")
            .select("ID", "Severity", "Start_Time", "End_Time", "County", "Start_Lat", "Start_Lng")
            .withColumn("Start_Date", F.to_date("Start_Time"))
            .withColumn("Start_HH", F.date_format("Start_Time", "HH:mm:ss"))
            .filter(F.col("Start_Date").isNotNull())
        )

        # Direct Write to Production
        # Using .mode("overwrite") will clear the existing directory and write new files
        print(f"Writing processed weather data to: {weather_out}")
        weather_processed.write.mode("overwrite").parquet(weather_out)

        print(f"Writing processed accident data to: {acc_out}")
        acc_processed.write.mode("overwrite").parquet(acc_out)

        print("Pipeline Job Completed Successfully.")

    except Exception as e:
        # Send an alert/email here
        print(f"!!! JOB FAILED Error: {str(e)}")
        sys.exit(1)

    finally:
        # Stop the Spark session
        spark.stop()

if __name__ == "__main__":
    main()